def text(im,s,x,y,px,col,outline=None,shadow=None,spacing=1):
    d=ImageDraw.Draw(im)
    def blocks(ox,oy,c,grow=0):
        cx=x
        for ch in s:
            g=G.get(ch.upper(),G[' '])
            for r,row in enumerate(g):
                for k,b in enumerate(row):
                    if b=='1': d.rectangle([cx+k*px+ox-grow,y+r*px+oy-grow,cx+(k+1)*px-1+ox+grow,y+(r+1)*px-1+oy+grow],fill=c)
            cx+=(5+spacing)*px
    if shadow: blocks(px//2+1,px//2+1,shadow,px//4 if outline else 0)
    if outline: blocks(0,0,outline,max(1,px//4))
    blocks(0,0,col)
